    fn parse_sample(text: &str) -> Message {
        // Same normalization the UI tabs apply before parsing.
        let normalized = text.replace("\r\n", "\r").replace('\n', "\r");
        parse_message(&normalized).expect("sample message must parse")
    }

    fn field(message: &Message, path: &str) -> Option<String> {
        Terser::new(message)
            .get(path)
            .expect("terser query must succeed")
            .map(|s| s.to_string())
    }

    fn segment_count(message: &Message, id: &str) -> usize {
        message.get_segments_by_id(id).len()
    }

    fn populated_field_count(message: &Message, id: &str) -> usize {
        message
            .get_segment_by_id(id)
            .map(|seg| seg.fields.iter().filter(|f| !f.is_empty()).count())
            .unwrap_or(0)
    }

